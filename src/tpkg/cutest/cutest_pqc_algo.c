static void check_sigtag_match(CuTest *tc) 
{
    edns_record_type edns;
    int i;

    edns_init_record(&edns);

    // Test a handle only sigtag
    edns.sigtag_enabled = 1;
    CuAssert(tc, "SIGTAG - Test No Handle Value", val_algo_sigtag_match(sigbytes_buffer, sigbytes_buffer_len, &edns) == 0);   

    // Test a matching signame
    edns.sigtag_enabled = 1;
    edns.sigtag_list[0].ladder_hash_len = sigbytes_hash_len;
    memcpy(edns.sigtag_list[0].ladder_hash, sigbytes_hash, sigbytes_hash_len);
    CuAssert(tc, "SIGTAG - Test Valid Matching Handle", val_algo_sigtag_match(sigbytes_buffer, sigbytes_buffer_len, &edns) == 1);     

    // Test an non-matching signame
    edns.sigtag_list[0].ladder_hash[8] = 0x01;
    CuAssert(tc, "SIGTAG - Test Valid Non-Matching Handle", val_algo_sigtag_match(sigbytes_buffer, sigbytes_buffer_len, &edns) == 0);    

    // Test NULL parameters
    memcpy(edns.sigtag_list[0].ladder_hash, sigbytes_hash, sigbytes_hash_len);    
    CuAssert(tc, "SIGTAG - Test Null Name Ptr", val_algo_sigtag_match(NULL, 256, &edns) == 0);
    CuAssert(tc, "SIGTAG - Test Null EDNS Ptr", val_algo_sigtag_match(sigbytes_buffer, sigbytes_buffer_len, NULL) == 0);

    // Test for multiple sigtags
    edns.sigtag_enabled = 1;
    edns.sigtag_list[0].ladder_hash_len = sigbytes_hash_len;
    memcpy(edns.sigtag_list[0].ladder_hash, sigbytes_hash, sigbytes_hash_len);    
    edns.sigtag_list[0].ladder_hash[8] = 0x01;

    edns.sigtag_list[1].ladder_hash_len = sigbytes_hash_len;
    memcpy(edns.sigtag_list[1].ladder_hash, sigbytes_hash, sigbytes_hash_len);
    CuAssert(tc, "SIGTAG - Test Valid Handle (Multiple SigTags)", val_algo_sigtag_match(sigbytes_buffer, sigbytes_buffer_len, &edns) == 1);      
}


static void check_leaf_index_from_condensed(CuTest *tc) {
    uint64_t leaf_index = 0;
    rr_type rr;
    uint8_t sig_data[] = {0x01, 0x00,0x00, // Flags
                             0x47,0xd4,0x0e,0xf2,0x94,0x7f,0x48,0xf0,0xca,0xbd,0x32,0x9f,0xa2,0x50,0x33,0x6c,  // SID
                             0xc0,0x81,0xf8,0x33,0x49,0xe9,0xa7,0x53,0xd7,0xa1,0xf7,0xef,0x1a,0x23,0xb1,0x3d,
                             0x97,0x35,0x98,0xb9,0x02,0x83,0xfe,0x2f,0xd3,0xe8,0x17,0x06,0x8e,0x68,0x15,0x85, // Randomizer
                             0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x08, // Leaf Index
                             0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x08, // Target Rung Left
                             0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x08, // Target Run Right
                             0x00,0x00}; // Sib Hash Count
    size_t sig_data_size =  77;

    rr.type = TYPE_RRSIG;
    rr.rdata_count = 8;
    rr.rdatas = malloc(8 * sizeof(rdata_atom_type *));
    // Setup the Sig Algo Record
    rr.rdatas[1].data = malloc(2);
    rr.rdatas[1].data[0] = 1;
    rr.rdatas[1].data[1] = 129;
    // Setup the condensed sig 
    rr.rdatas[8].data = malloc(1+sig_data_size);
    rr.rdatas[8].data[0] = sig_data_size;
    memcpy(&rr.rdatas[8].data[1], sig_data, sig_data_size);

    CuAssert(tc, "SIGTAG check leaf index determination - Valid", val_algo_get_leaf_index_from_condensed(&rr, &leaf_index) == MTL_OK);
    CuAssert(tc, "SIGTAG check leaf index determination - Valid", leaf_index == 8);

    // Check invalid length buffers
    rr.rdatas[8].data[0] = sig_data_size/2;
    CuAssert(tc, "SIGTAG check leaf index determination - Valid", val_algo_get_leaf_index_from_condensed(&rr, &leaf_index) == MTL_BUFFER_ERROR);
    CuAssert(tc, "SIGTAG check leaf index determination - Valid", leaf_index == 0);

    // Test Null Parameters
    CuAssert(tc, "SIGTAG check leaf index determination - NULL", val_algo_get_leaf_index_from_condensed(NULL, &leaf_index) == MTL_NULL_PARAMETERS);
    CuAssert(tc, "SIGTAG check leaf index determination - NULL", val_algo_get_leaf_index_from_condensed(&rr, NULL) == MTL_NULL_PARAMETERS);

    free(rr.rdatas[1].data);
    free(rr.rdatas[8].data);
    free(rr.rdatas);

}



